/* ============================================================================
   src/20_lyrics.js — the running order of the film.

   Reads the generated cue table and turns it into the object the renderer and
   every plate work against. Timings are the measured ones from the supplied
   lyric timeline, not a metronome grid: the recording is played by a person
   and sits about 0.11 s off a strict 130 BPM lattice, so the words follow the
   performer while the MIDI supplies the accents. Keeping those two jobs on
   separate sources is deliberate — mixing them produces a film that is
   rhythmically tidy and lyrically late.

   Generated by _build/parse-lrc.js. Edit the table there and re-run it; the
   self-test in 50_selftest.js compares this against the copy embedded in
   index.html on every load.
   ==========================================================================*/
(function (EM) {
  'use strict';

  var RAW = EM.CUES || [];
  var END = EM.AUDIO_END;

  var C = [];
  for (var i = 0; i < RAW.length; i++) {
    C.push({
      i: i,
      t: RAW[i][0],
      text: RAW[i][1],
      scene: RAW[i][2],
      repeat: RAW[i][3],
      /* may this plate fade out through the NEXT one? False for plates whose
         picture is the sung word itself — see drawSequence in 15_sceneapi.js
         for why letting those bleed puts words on screen that the song is not
         singing. */
      bleed: RAW[i].length < 5 ? true : !!RAW[i][4],
      end: END,
      dur: 0
    });
  }
  for (i = 0; i < C.length; i++) {
    C[i].end = (i + 1 < C.length) ? C[i + 1].t : END;
    /* a floor on duration: two lines 120 ms apart must still each get a
       visible entrance, and dividing by a tiny duration amplifies float noise */
    C[i].dur = Math.max(0.12, C[i].end - C[i].t);
  }

  /* --------------------------------------------------------------------------
     HELD CUES.

     A cue listed in HOLD has no plate of its own: the picture from the PREVIOUS
     cue simply keeps playing through it. Its time is given to that previous cue,
     so the previous cue's duration — and therefore its fade maths — spans the
     whole stretch.

     Crucially, `at(t)` RESOLVES a held cue away: inside a held stretch it
     returns the cue that actually owns the picture. An earlier version left
     `at()` returning the held cue and had drawSequence look up "the cue before
     this one", which meant the plate was driven by the held cue's own progress
     instead of the owner's — so the word faded in and immediately started
     leaving, and four seconds of the shot sat at a third brightness.

     Resolving here means every consumer — the renderer, the debug overlay, the
     verifier — sees one continuous shot, and no plate has to know it is being
     extended.
     ------------------------------------------------------------------------ */
  var HOLD = { outro: true };
  for (i = 0; i < C.length; i++) {
    C[i].held = !!HOLD[C[i].scene] || C[i].scene === null;
  }
  /* an owner's span runs through all the held cues that follow it */
  for (i = 0; i < C.length; i++) {
    if (C[i].held) continue;
    var j = i + 1;
    while (j < C.length && C[j].held) j++;
    if (j > i + 1) {
      C[i].end = (j < C.length) ? C[j].t : END;
      C[i].dur = Math.max(0.12, C[i].end - C[i].t);
    }
  }
  /* the map from any cue to the cue that owns the picture at that moment */
  var OWNER = new Array(C.length);
  var lastOwner = 0;
  for (i = 0; i < C.length; i++) {
    if (!C[i].held) lastOwner = i;
    OWNER[i] = lastOwner;
  }
  var OWNERS = [];
  for (i = 0; i < C.length; i++) {
    if (!C[i].held) OWNERS.push(C[i]);
  }
  EM.LyricsHeld = HOLD;

  /* binary search for the line active at t. Called once per frame, so it is
     O(log n) and allocation-free. A held cue resolves to the cue that owns the
     picture at that moment — see the note above. */
  function indexAt(t) {
    if (!C.length) return -1;
    var lo = 0, hi = C.length - 1, best = 0;
    while (lo <= hi) {
      var mid = (lo + hi) >> 1;
      if (C[mid].t <= t + 1e-6) { best = mid; lo = mid + 1; } else { hi = mid - 1; }
    }
    return OWNER[best];
  }

  function at(t) { return C[indexAt(t)]; }

  var BY_SCENE = Object.create(null);
  for (i = 0; i < C.length; i++) BY_SCENE[C[i].scene] = C[i];

  /* how many times this exact line is sung across the song */
  var TOTALS = Object.create(null);
  for (i = 0; i < C.length; i++) {
    var key = C[i].text.replace(/[^A-Za-z]/g, '').toUpperCase() || ('_' + i);
    TOTALS[key] = (TOTALS[key] || 0) + 1;
  }
  function repeatTotal(cue) {
    if (!cue) return 1;
    var key = cue.text.replace(/[^A-Za-z]/g, '').toUpperCase() || ('_' + cue.i);
    return TOTALS[key] || 1;
  }

  function toLRC() {
    var out = 'world.execute(me); — timeline\n';
    for (var k = 0; k < C.length; k++) {
      out += '[' + EM.fmtTime(C[k].t) + ']' + C[k].text + '\n';
    }
    return out;
  }

  /* the text of the next line, for the HUD's "next" read-out */
  function next(t) {
    var i = indexAt(t);
    return (i + 1 < C.length) ? C[i + 1] : null;
  }

  EM.Lyrics = {
    cues: C,
    count: C.length,
    at: at,
    indexAt: indexAt,
    byScene: BY_SCENE,
    repeatTotal: repeatTotal,
    next: next,
    toLRC: toLRC,
    duration: END
  };
})(window.EM);
